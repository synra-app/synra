/**
 * v3 plugin contract — keep every Vue public API alive in the host
 * build's tree-shake pass.
 *
 * The plugin SDK tells plugin bundles to keep `vue` external (so the
 * plugin and host share one Vue runtime via importmap). Plugin bundles
 * compiled from `.vue` SFCs import Vue compiler helpers by their public
 * names — `createElementVNode`, `createElementBlock`, `Transition`,
 * etc. — which the importmap resolves to the host's `vendor-vue` chunk.
 *
 * `vue` is published as a thin ESM stub that does `export * from
 * '@vue/runtime-dom'`. The `@vue/runtime-dom` build itself only
 * exposes `createBaseVNode as createElementVNode` and the runtime-dom
 * helpers (`Transition`, `withKeys`, `withModifiers`, ...). When the
 * host tree-shakes its build, Rollup drops any name the host's own
 * code never references — so the `vendor-vue` chunk ends up exporting
 * `createElementBlock` but not `createElementVNode`, and `Transition`
 * is missing entirely. When the chat plugin then mounts on Android,
 * its compiled render function calls `createElementVNode(...)` against
 * `undefined`, the patch path bails, and Vue's `setRef` reads
 * `null.refs` — surface error
 * `TypeError: Cannot read properties of null (reading 'refs')`.
 *
 * This file re-exports the full public Vue surface as named bindings.
 * A bare `export { Transition } from '@vue/runtime-dom'` is NOT
 * sufficient — Rollup tree-shake would see that nothing in the host
 * graph uses `Transition` and inline the symbol into use sites instead
 * of emitting a live `export { Transition }` in the vendor-vue chunk.
 * To force a live binding we additionally publish every name onto
 * `globalThis.__SYNRA_VUE_PUBLIC_API__` — a side effect that any
 * tree-shaker has to honor. The map is also handy for debugging which
 * Vue helpers the plugin runtime expects.
 */
