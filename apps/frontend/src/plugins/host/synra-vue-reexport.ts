// `mergeModels` lives in `@vue/runtime-core`. It is part of the public
// runtime API (compiled `.vue` SFCs reference it directly), but Vue's
// own `.d.ts` does not declare it (it expects apps to use
// `defineModel` instead). Ignore the missing-type error so rollup can
// still resolve it through the runtime export.
// @ts-ignore -- runtime export not declared in @vue/runtime-core/dist/runtime-core.d.ts
import { mergeModels } from '@vue/runtime-core'

// Force a live `createElementVNode` binding in the vendor-vue chunk's
// export block. `createElementVNode` is implemented in
// `@vue/runtime-core` as `createBaseVNode` and exported via the
// `createBaseVNode as createElementVNode` alias. When we `import {
// createElementVNode } from '@vue/runtime-core'` and then `export {
// createElementVNode }` from this file, Rollup traces the alias back
// to `createBaseVNode` and emits `Os as createBaseVNode` in the chunk
// instead of `Os as createElementVNode` — the plugin bundle's
// `import { createElementVNode } from 'vue'` then resolves to
// `undefined`. A standalone `export ... from` statement preserves
// the source's public name through to the chunk's export block.
export { createElementVNode } from '@vue/runtime-core'

